"""Pixel sprite of the 역학원 master (original character), 32 x 32.

Builds the frames from one base drawing and writes dist/master.js.
Run: python3 tools/sprite_master.py
"""
import json
from pathlib import Path

W, H = 32, 32
PALETTE = {
    "o": "#2a1c14",  # outline
    "h": "#1b1b22",  # hair
    "H": "#454556",  # hair highlight
    "s": "#f0c29a",  # skin
    "S": "#d49a74",  # skin shadow
    "b": "#2a1c14",  # brows
    "g": "#c9a227",  # gold glasses frame
    "l": "#e8f3ff",  # lens
    "e": "#1b1b22",  # eye
    "m": "#a8524a",  # mouth
    "M": "#5a1f1c",  # open mouth
    "c": "#d8b24a",  # glasses chain
    "w": "#f6f7fb",  # shirt
    "W": "#c9d0e0",  # shirt shadow
    "t": "#c4262e",  # tie
    "T": "#86161c",  # tie shadow / knot
    "v": "#5b5f6b",  # vest
    "V": "#3e414b",  # vest shadow
    "k": "#e9d9a8",  # vest button
}

def blank():
    return [["." for _ in range(W)] for _ in range(H)]

def put(g, x, y, ch):
    if 0 <= x < W and 0 <= y < H:
        g[y][x] = ch

def row(g, y, text, x0=0):
    for i, ch in enumerate(text):
        if ch != " ":
            put(g, x0 + i, y, ch)

def base():
    g = blank()
    # head (outline at x=7 and x=23)
    row(g, 1, "ooooooooooo", 10)
    row(g, 2, "oohhhhhhhhhhhoo", 8)
    row(g, 3, "ohhhhHHHHhhhhhho", 7)
    row(g, 4, "ohhhHHhhhhhhhhho", 7)
    row(g, 5, "ohhhhhhhhssssshho", 7)  # side part, forehead shows on the right
    row(g, 6, "ohhsssssssssssho", 7)
    row(g, 7, "ohsssssssssssso", 8) ; put(g, 7, 7, "o")
    row(g, 8, "osbbbbsssssbbbbso", 7)
    # glasses
    row(g, 9, "ogggggggggggggggo", 7)
    row(g, 10, "gglleelgsgleellgg", 7)
    row(g, 11, "oglllllgsglllllgo", 7)
    row(g, 12, "osgggggsSsgggggso", 7)
    # nose, mouth, chin
    row(g, 13, "osssssssSssssssso", 7)
    row(g, 14, "ossssssSSSsssssso", 7)
    row(g, 15, "osssssssssssssso", 7) ; put(g, 23, 15, "o")
    row(g, 16, "osssssmmmmmssssso", 7)
    row(g, 17, "ossssssssssssso", 8)
    row(g, 18, "ossssssssssso", 9)
    row(g, 19, "oosssssssoo", 10)
    row(g, 20, "oSSSSSSSo", 11)
    # shoulders: shirt collar, tie, vest
    for y in range(21, 32):
        half = min(13, 6 + (y - 21) * 2)
        x0, x1 = 15 - half, 15 + half
        for x in range(x0, x1 + 1):
            put(g, x, y, "v")
        put(g, x0, y, "o"); put(g, x1, y, "o")
        if half > 3:
            put(g, x0 + 1, y, "V"); put(g, x1 - 1, y, "V")
    # shirt V and collar
    for y in range(21, 32):
        spread = max(1, 4 - (y - 21) // 3)
        for x in range(15 - spread, 15 + spread + 1):
            put(g, x, y, "w")
    row(g, 21, "owwwwo", 13) ; row(g, 22, "Wwo", 12); row(g, 22, "owW", 17)
    # tie
    row(g, 21, "TT", 15) ; put(g, 14, 21, "T")
    for y in range(22, 32):
        put(g, 15, y, "t")
        if y > 23:
            put(g, 14, y, "t"); put(g, 16, y, "T")
    # vest buttons
    for y in (25, 28, 31):
        put(g, 18, y, "k")
    # glasses chain from the temples down around the neck
    for y in range(11, 21):
        put(g, 6, y, "c"); put(g, 24, y, "c")
    for i, y in enumerate(range(21, 24)):
        put(g, 7 + i, y, "c"); put(g, 23 - i, y, "c")
    return g

def blink(g):
    g = [r[:] for r in g]
    for x in range(W):
        if g[10][x] == "e":
            g[10][x] = "l"
            g[11][x] = "e"
    return g

def talk(g):
    g = [r[:] for r in g]
    row(g, 16, "mMMMm", 13)
    row(g, 17, "MMM", 14)
    return g

def point(g):
    """Raises a hand with the index finger up beside the face (viewer's right).

    The forearm comes up from the shoulder, so only a short grey sleeve shows,
    with the white shirt cuff at the wrist.
    """
    g = [r[:] for r in g]
    # grey jacket sleeve from below the frame edge up to the wrist (row 18),
    # so the arm runs out of the picture instead of stopping mid-air
    for y in range(18, H):
        for x in range(25, 30):
            put(g, x, y, "v")
        put(g, 29, y, "V")
        put(g, 24, y, "o"); put(g, 30, y, "o")
    # shirt cuff
    row(g, 17, "owwwwWo", 24)
    # hand: index finger, knuckles, thumb
    row(g, 8, "o", 26)
    row(g, 9, "oso", 25)
    row(g, 10, "oso", 25)
    row(g, 11, "osoooo", 25)
    row(g, 12, "osssSo", 25)
    row(g, 13, "osssSso", 24)
    row(g, 14, "osssSo", 25)
    row(g, 15, "osssSo", 25)
    row(g, 16, "oSSSSo", 25)
    return g

frames = {"idle": base()}
frames["blink"] = blink(frames["idle"])
frames["talk"] = talk(frames["idle"])
frames["point"] = point(frames["idle"])
frames["pointTalk"] = talk(frames["point"])

# Show only the shoulders: the drawing is cut below the collar and tie knot.
CROP_H = 26
out = {
    "w": W, "h": CROP_H, "palette": PALETTE,
    "frames": {k: ["".join(r) for r in v[:CROP_H]] for k, v in frames.items()},
}
js = "// Generated by tools/sprite_master.py. Pixel art of the 역학원 master (original character).\nexport const MASTER = " + json.dumps(out, ensure_ascii=False) + ";\n"
Path(__file__).resolve().parent.parent.joinpath("dist", "master.js").write_text(js)
for k, v in frames.items():
    print(k)
    print("\n".join("".join(r) for r in v))
    break
